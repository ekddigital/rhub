/* ─── Document Metadata ────────────────────────────────────────── */
export interface DocumentMeta {
  title: string;
  subtitle?: string;
  author?: string;
  date?: string;
  version?: string;
  reference?: string;
  confidential?: boolean;
  /** Show table of contents */
  showTOC?: boolean;
  /** Maximum heading depth for TOC (1-6, default 3) */
  tocMaxLevel?: number;
  /** Show cover page */
  showCover?: boolean;
  /** Cover page visual style */
  coverStyle?: CoverStyle;
  /** Show separate List of Tables page */
  showListOfTables?: boolean;
  /** Show separate List of Figures page */
  showListOfFigures?: boolean;
}

/* ─── Table of Contents ────────────────────────────────────────── */
export interface TOCEntry {
  id: string;
  text: string;
  level: number;
  number: string;
  page?: number;
}

/* ─── Complete Document Model ──────────────────────────────────── */
export interface DocumentModel {
  meta: DocumentMeta;
  children: DocumentNode[];
  /** Auto-generated by TOC builder */
  toc?: TOCEntry[];
  /** Auto-generated list of tables */
  listOfTables?: TOCEntry[];
  /** Auto-generated list of figures */
  listOfFigures?: TOCEntry[];
}

/* ─── Template Configuration ───────────────────────────────────── */
export interface TemplateConfig {
  id: string;
  name: string;
  description: string;
  /** Show letterhead header */
  showHeader: boolean;
  /** Show footer with page numbers */
  showFooter: boolean;
  /** First page different from rest */
  firstPageDifferent: boolean;
  /** Show table of contents */
  showTOC: boolean;
  /** Show cover page */
  showCover: boolean;
  /** Show separate List of Tables page */
  showListOfTables?: boolean;
  /** Show separate List of Figures page */
  showListOfFigures?: boolean;
  /** Margin preset */
  margins: "standard" | "narrow" | "wide";
}

/* ─── Export Options ───────────────────────────────────────────── */
export interface ExportOptions {
  format: "pdf" | "docx";
  filename: string;
  template: string;
  includeBookmarks: boolean;
  includeTOC: boolean;
  quality: "draft" | "standard" | "high";
}
